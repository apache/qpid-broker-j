package org.apache.qpid.server.security;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.security.GeneralSecurityException;
import java.util.Base64;
import java.util.Map;

import javax.net.ssl.KeyManager;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import org.apache.qpid.server.configuration.IllegalConfigurationException;
import org.apache.qpid.server.model.Broker;
import org.apache.qpid.server.model.BrokerModel;
import org.apache.qpid.server.model.BrokerTestHelper;
import org.apache.qpid.server.model.ConfiguredObjectFactory;
import org.apache.qpid.server.model.KeyStore;
import org.apache.qpid.server.security.certificate.CertificateGenerators;
import org.apache.qpid.server.security.certificate.CertificateGeneratorsTestHelper;
import org.apache.qpid.test.utils.UnitTestBase;
import org.apache.qpid.test.utils.tls.KeyCertificatePair;
import org.apache.qpid.test.utils.tls.TlsResourceBuilder;

/** broker-core has no certificate generator on its classpath; tests that need one supply it. */
class AutoGeneratedSelfSignedKeyStoreWithoutGeneratorTest extends UnitTestBase
{
    private static final Broker<?> BROKER = BrokerTestHelper.createBrokerMock();
    private static final ConfiguredObjectFactory FACTORY = BrokerModel.getInstance().getObjectFactory();
    private static final String NAME = "myKeyStore";
    private static final String TYPE = "AutoGeneratedSelfSigned";
    private static final String PLUGIN = "qpid-broker-plugins-certificate-generator-bouncycastle";

    @BeforeEach
    void setUp()
    {
        CertificateGeneratorsTestHelper.reset();
    }

    @AfterEach
    void tearDown()
    {
        CertificateGeneratorsTestHelper.reset();
    }

    @Test
    void typeIsRegistered()
    {
        assertFalse(CertificateGenerators.isAvailable());
        assertTrue(FACTORY.getSupportedTypes(KeyStore.class).contains(TYPE));
    }

    @Test
    void storedKeyStoreLoads() throws Exception
    {
        final KeyCertificatePair keyCertPair = TlsResourceBuilder.createSelfSigned("CN=Qpid");
        final AutoGeneratedSelfSignedKeyStore<?> keyStore = createStoredKeyStore(keyCertPair);

        final KeyManager[] keyManagers = keyStore.getKeyManagers();
        assertEquals(1, keyManagers.length, "Unexpected number of key managers");
        assertNotNull(keyManagers[0]);
        assertEquals(encode(keyCertPair.certificate().getEncoded()), keyStore.getEncodedCertificate());
    }

    @Test
    void creationFailsWithClearMessage()
    {
        final Map<String, Object> attributes = Map.of(AutoGeneratedSelfSignedKeyStore.NAME, NAME,
                                                      AutoGeneratedSelfSignedKeyStore.TYPE, TYPE);

        final IllegalConfigurationException thrown = assertThrows(IllegalConfigurationException.class,
                () -> FACTORY.create(KeyStore.class, attributes, BROKER));
        assertTrue(thrown.getMessage().contains(PLUGIN), "Unexpected message: " + thrown.getMessage());
        assertTrue(thrown.getMessage().contains("'" + NAME + "'"), "Unexpected message: " + thrown.getMessage());
    }

    @Test
    void creationRejectsNonPositiveDuration()
    {
        final Map<String, Object> attributes = Map.of(AutoGeneratedSelfSignedKeyStore.NAME, NAME,
                                                      AutoGeneratedSelfSignedKeyStore.TYPE, TYPE,
                                                      AutoGeneratedSelfSignedKeyStore.DURATION_IN_MONTHS, 0);

        final IllegalConfigurationException thrown = assertThrows(IllegalConfigurationException.class,
                () -> FACTORY.create(KeyStore.class, attributes, BROKER));
        assertTrue(thrown.getMessage().contains("'" + AutoGeneratedSelfSignedKeyStore.DURATION_IN_MONTHS + "'"),
                   "Unexpected message: " + thrown.getMessage());
    }

    @Test
    void creationFailureReportsUnusableGenerator()
    {
        final String reason = "certificate generator 'BouncyCastle' is installed but a library it requires is missing";
        final Map<String, Object> attributes = Map.of(AutoGeneratedSelfSignedKeyStore.NAME, NAME,
                                                      AutoGeneratedSelfSignedKeyStore.TYPE, TYPE);

        try (final CertificateGeneratorsTestHelper.Reset ignored =
                     CertificateGeneratorsTestHelper.useNoGenerator(reason))
        {
            final IllegalConfigurationException thrown = assertThrows(IllegalConfigurationException.class,
                    () -> FACTORY.create(KeyStore.class, attributes, BROKER));
            assertTrue(thrown.getMessage().contains(reason), "Unexpected message: " + thrown.getMessage());
        }
    }

    @Test
    void regenerateFailsAndKeepsCertificate() throws Exception
    {
        final KeyCertificatePair keyCertPair = TlsResourceBuilder.createSelfSigned("CN=Qpid");
        final AutoGeneratedSelfSignedKeyStore<?> keyStore = createStoredKeyStore(keyCertPair);

        final IllegalConfigurationException thrown =
                assertThrows(IllegalConfigurationException.class, keyStore::regenerateCertificate);
        assertTrue(thrown.getMessage().contains(PLUGIN), "Unexpected message: " + thrown.getMessage());
        assertEquals(encode(keyCertPair.certificate().getEncoded()), keyStore.getEncodedCertificate());
        assertEquals(encode(keyCertPair.privateKey().getEncoded()), keyStore.getEncodedPrivateKey());
    }

    @Test
    void regenerateWithFailingGeneratorKeepsCertificate() throws Exception
    {
        final KeyCertificatePair keyCertPair = TlsResourceBuilder.createSelfSigned("CN=Qpid");
        final AutoGeneratedSelfSignedKeyStore<?> keyStore = createStoredKeyStore(keyCertPair);
        try (final CertificateGeneratorsTestHelper.Reset ignored =
                     CertificateGeneratorsTestHelper.useGenerator("Failing", request ->
                     {
                         throw new GeneralSecurityException("signing refused");
                     }))
        {
            final IllegalConfigurationException thrown =
                    assertThrows(IllegalConfigurationException.class, keyStore::regenerateCertificate);
            assertTrue(thrown.getMessage().contains("'" + NAME + "'"), "Unexpected message: " + thrown.getMessage());
            assertTrue(thrown.getMessage().contains("signing refused"), "Unexpected message: " + thrown.getMessage());
            assertTrue(thrown.getMessage().contains("'" + keyStore.getSignatureAlgorithm() + "'"),
                       "Unexpected message: " + thrown.getMessage());
        }
        assertEquals(encode(keyCertPair.certificate().getEncoded()), keyStore.getEncodedCertificate());
        assertEquals(encode(keyCertPair.privateKey().getEncoded()), keyStore.getEncodedPrivateKey());
    }

    private AutoGeneratedSelfSignedKeyStore<?> createStoredKeyStore(final KeyCertificatePair keyCertPair)
            throws Exception
    {
        final Map<String, Object> attributes = Map.of(
                AutoGeneratedSelfSignedKeyStore.NAME, NAME,
                AutoGeneratedSelfSignedKeyStore.TYPE, TYPE,
                AutoGeneratedSelfSignedKeyStore.ENCODED_CERTIFICATE, encode(keyCertPair.certificate().getEncoded()),
                AutoGeneratedSelfSignedKeyStore.ENCODED_PRIVATE_KEY, encode(keyCertPair.privateKey().getEncoded()));
        return (AutoGeneratedSelfSignedKeyStore<?>) FACTORY.create(KeyStore.class, attributes, BROKER);
    }

    private static String encode(final byte[] bytes)
    {
        return Base64.getEncoder().encodeToString(bytes);
    }
}
