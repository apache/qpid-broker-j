package org.apache.qpid.tests.http.endtoend.keystore;

import static jakarta.servlet.http.HttpServletResponse.SC_CREATED;
import static jakarta.servlet.http.HttpServletResponse.SC_OK;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotEquals;

import java.io.ByteArrayInputStream;
import java.security.cert.CertificateFactory;
import java.security.cert.X509Certificate;
import java.util.Base64;
import java.util.Map;

import javax.security.auth.x500.X500Principal;

import org.junit.jupiter.api.Test;

import org.apache.qpid.server.security.AutoGeneratedSelfSignedKeyStore;
import org.apache.qpid.tests.http.HttpTestBase;

/** Certificate generation by a running broker with the Bouncy Castle certificate generator plugin installed. */
public class AutoGeneratedSelfSignedKeyStoreTest extends HttpTestBase
{
    @Test
    public void createAndRegenerate() throws Exception
    {
        final String url = "keystore/" + getTestName();
        getHelper().submitRequest(url, "PUT", Map.of(AutoGeneratedSelfSignedKeyStore.NAME, getTestName(),
                                                     AutoGeneratedSelfSignedKeyStore.TYPE, "AutoGeneratedSelfSigned"),
                                  SC_CREATED);

        final X509Certificate certificate = getCertificate(url);
        assertEquals(new X500Principal("CN=Qpid"), certificate.getSubjectX500Principal());
        assertEquals(new X500Principal("CN=Qpid"), certificate.getIssuerX500Principal());
        assertEquals(-1, certificate.getBasicConstraints(), "Certificate must not be a CA certificate");
        certificate.verify(certificate.getPublicKey());

        getHelper().submitRequest(url + "/regenerateCertificate", "POST", Map.of(), SC_OK);

        final X509Certificate regenerated = getCertificate(url);
        assertNotEquals(certificate.getSerialNumber(), regenerated.getSerialNumber());
        assertNotEquals(certificate.getPublicKey(), regenerated.getPublicKey());
        regenerated.verify(regenerated.getPublicKey());
    }

    private X509Certificate getCertificate(final String url) throws Exception
    {
        final Map<String, Object> keyStore = getHelper().getJsonAsMap(url);
        final byte[] encoded =
                Base64.getDecoder().decode((String) keyStore.get(AutoGeneratedSelfSignedKeyStore.ENCODED_CERTIFICATE));
        return (X509Certificate) CertificateFactory.getInstance("X.509")
                .generateCertificate(new ByteArrayInputStream(encoded));
    }
}
